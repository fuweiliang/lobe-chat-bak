import { existsSync, readdirSync, readFileSync, renameSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('../../', import.meta.url));
const retainedPages = new Set([
  'spa/[variants]/[[...path]]/route.ts',
  'spa-auth/[locale]/[[...path]]/route.ts',
  '(backend)/f/[id]/route.ts',
]);

// These modules keep their existing auth, request/response types, cookies and streaming.
// Specific routes precede their catch-all siblings.
const groups = {
  api: [
    'api/auth/check-user', 'api/auth/resolve-username', 'api/auth/[...all]',
    'api/version', 'api/agent/stream', 'api/agent/[[...route]]',
  ],
  trpc: ['trpc/lambda/[trpc]', 'trpc/async/[trpc]', 'trpc/tools/[trpc]', 'trpc/mobile/[trpc]'],
  webapi: [
    'webapi/auth/spa-config', 'webapi/chat/[provider]',
    'webapi/models/[provider]/pricing', 'webapi/models/[provider]',
    'webapi/user/avatar/[id]/[image]', 'webapi/document/events',
  ],
  oidc: [
    'oidc/client-metadata/[clientId]', 'oidc/consent', 'oidc/clear-session',
    'oidc/handoff', 'oidc/interaction/[uid]', 'oidc/callback/desktop', 'oidc/[...oidc]',
  ],
};

function filesUnder(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((item) => {
    const file = path.join(directory, item.name);
    return item.isDirectory() ? filesUnder(file) : [file];
  });
}

function routePattern(route) {
  const catchAll = [];
  let pattern = '^';
  for (const segment of route.split('/')) {
    const optional = /^\[\[\.\.\.(\w+)\]\]$/.exec(segment);
    const required = /^\[\.\.\.(\w+)\]$/.exec(segment);
    const dynamic = /^\[(\w+)\]$/.exec(segment);
    if (optional) {
      catchAll.push(optional[1]);
      pattern += `(?:/(?<${optional[1]}>.+))?`;
    } else if (required) {
      catchAll.push(required[1]);
      pattern += `/(?<${required[1]}>.+)`;
    } else if (dynamic) {
      pattern += `/(?<${dynamic[1]}>[^/]+)`;
    } else {
      pattern += '/' + segment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }
  }
  return { source: pattern + '$', catchAll };
}

export function prepareLiteDeployment(root = projectRoot, checkOnly = false) {
  const app = path.join(root, 'src/app');
  const generated = path.join(app, '(lite)');
  if (!checkOnly) {
    rmSync(generated, { recursive: true, force: true });
    for (const file of filesUnder(app)) {
      if (file.endsWith('/route.liteSource.ts')) renameSync(file, file.replace(/\.liteSource\.ts$/, '.ts'));
    }
  }
  const originalRoutes = filesUnder(app).filter((file) => file.endsWith('/route.ts') && !file.startsWith(generated + path.sep));
  for (const routes of Object.values(groups)) {
    for (const route of routes) {
      const file = path.join(app, '(backend)', route, 'route.ts');
      if (!existsSync(file)) throw new Error(`Missing retained backend route: ${route}`);
    }
  }
  const activeRoutes = [...retainedPages, ...Object.keys(groups).map((group) => `(lite)/${group}/[[...litePath]]/route.ts`)];
  if (checkOnly) return { originalRouteCount: originalRoutes.length, activeRouteCount: activeRoutes.length, activeRoutes };

  for (const file of originalRoutes) {
    const relative = path.relative(app, file).split(path.sep).join('/');
    if (!retainedPages.has(relative)) renameSync(file, file.replace(/\.ts$/, '.liteSource.ts'));
  }
  for (const [group, routes] of Object.entries(groups)) {
    const output = path.join(generated, group, '[[...litePath]]', 'route.ts');
    const definitions = routes.map((route) => {
      const { source, catchAll } = routePattern(route);
      const module = `@/app/(backend)/${route}/route.liteSource`;
      return `  { pattern: new RegExp(${JSON.stringify(source)}), catchAll: ${JSON.stringify(catchAll)}, load: () => import(${JSON.stringify(module)}) },`;
    });
    mkdirSync(path.dirname(output), { recursive: true });
    writeFileSync(output, [
      '// Generated by scripts/liteDeployment/prepare.mjs. Do not commit generated routes.',
      "import { dispatchLiteRequest } from '@/libs/next/lite/dispatch.mjs';",
      'export const runtime = "nodejs";',
      'export const maxDuration = 300;',
      'const routes = [', ...definitions, '];',
      'const handler = (request: Request) => dispatchLiteRequest(request, routes);',
      'export { handler as GET, handler as POST, handler as PUT, handler as PATCH, handler as DELETE, handler as OPTIONS, handler as HEAD };',
      '',
    ].join('\n'));
  }
  return { originalRouteCount: originalRoutes.length, activeRouteCount: activeRoutes.length, activeRoutes };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(prepareLiteDeployment(projectRoot, process.argv.includes('--check')), null, 2));
}
